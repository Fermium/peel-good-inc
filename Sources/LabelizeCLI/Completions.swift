import Foundation

/// Shell completion scripts generated from `Manual`. Printer names and sizes are asked of
/// `peelgood printers --names` and `peelgood sizes --names` as you type.
public enum Completions {
    public enum Shell: String, CaseIterable, Sendable {
        case zsh, bash, fish

        /// The line to add to a startup file (or run once for fish).
        public var installLine: String {
            switch self {
            case .zsh: #"eval "$(peelgood completions zsh)""#
            case .bash: #"eval "$(peelgood completions bash)""#
            case .fish: "peelgood completions fish > ~/.config/fish/completions/peelgood.fish"
            }
        }

        public var startupFile: String {
            switch self {
            case .zsh: "~/.zshrc"
            case .bash: "~/.bash_profile"
            case .fish: "~/.config/fish/completions"
            }
        }

        /// File names Homebrew's completion stanzas expect.
        public var fileName: String {
            switch self {
            case .zsh: "_peelgood"
            case .bash: "peelgood.bash"
            case .fish: "peelgood.fish"
            }
        }
    }

    public static func script(for shell: Shell) -> String {
        switch shell {
        case .zsh: zsh()
        case .bash: bash()
        case .fish: fish()
        }
    }

    static let extensions = ["pdf", "svg", "png", "jpg", "jpeg", "heic", "tif", "tiff", "gif", "webp"]
    static var commands: [CLICommand] { Manual.visibleCommands }

    /// First sentence, without characters the shells treat specially.
    static func short(_ help: String) -> String {
        let first = help.split(separator: ".", maxSplits: 1).first.map(String.init) ?? help
        return first.replacingOccurrences(of: "'", with: "").replacingOccurrences(of: "[", with: "(").replacingOccurrences(of: "]", with: ")")
            .replacingOccurrences(of: ":", with: " -").replacingOccurrences(of: "\"", with: "")
    }

    // MARK: zsh

    static func zsh() -> String {
        var s = """
        #compdef \(Manual.names.joined(separator: " "))
        # zsh completion for \(Manual.tool). Generated by `peelgood completions zsh`.

        _peelgood_printers() {
          local -a items; items=(${(f)"$(command $service printers --names 2>/dev/null)"})
          _describe -t printers 'printer' items
        }

        _peelgood_sizes() {
          local -a items; items=(${(f)"$(command $service sizes --names 2>/dev/null)"})
          _describe -t sizes 'size' items
        }

        _peelgood() {
          local curcontext="$curcontext" state line
          typeset -A opt_args
          _arguments -C \\
            '(- *)'{-V,--version}'[Show the version]' \\
            '(- *)'{-h,--help}'[Help]' \\
            '1: :->command' \\
            '*:: :->args'
          case $state in
            command)
              local -a commands
              commands=(

        """
        for c in commands {
            for name in [c.name] + c.aliases { s += "        '\(name):\(short(c.summary))'\n" }
        }
        s += """
              )
              _describe -t commands 'command' commands
              ;;
            args)
              case $words[1] in

        """
        for c in commands {
            s += "        " + ([c.name] + c.aliases).joined(separator: "|") + ")\n          _arguments \\\n"
            for o in c.visibleOptions + Manual.globalOptions {
                s += "            " + zshSpec(o) + " \\\n"
            }
            for (i, a) in c.arguments.enumerated() {
                let action = zshAction(a.completion, choices: a.choices)
                s += a.variadic ? "            '*:\(a.name):\(action)' \\\n" : "            '\(i + 1)::\(a.name):\(action)' \\\n"
            }
            s.removeLast(3)
            s += "\n          ;;\n"
        }
        s += """
              esac
              ;;
          esac
        }

        if [[ "$funcstack[1]" = "_peelgood" ]]; then
          _peelgood "$@"
        else
          compdef _peelgood \(Manual.names.joined(separator: " "))
        fi

        """
        return s
    }

    static func zshSpec(_ o: CLIOption) -> String {
        let help = "[\(short(o.help))]"
        let names = o.short.map { "'(-\($0) --\(o.name))'{-\($0),--\(o.name)}'" } ?? "'--\(o.name)"
        guard let value = o.value else { return names + help + "'" }
        let action = zshAction(o.completion, choices: o.choices)
        return names + help + ":\(value.lowercased()):\(action)'"
    }

    static func zshAction(_ completion: CLIOption.Completion, choices: [String]) -> String {
        switch completion {
        case .none: " "
        case .file: "_files -g \"*.(\(extensions.joined(separator: "|")))(-.)\""
        case .directory: "_files -/"
        case .printers: "_peelgood_printers"
        case .sizes: "_peelgood_sizes"
        case .choices: "(\(choices.joined(separator: " ")))"
        }
    }

    // MARK: bash

    static func bash() -> String {
        let names = commands.flatMap { [$0.name] + $0.aliases }.joined(separator: " ")
        var s = """
        # bash completion for \(Manual.tool). Generated by `peelgood completions bash`.
        _peelgood() {
          local cur prev cmd opts files="" dirs=""
          cur="${COMP_WORDS[COMP_CWORD]}"
          prev="${COMP_WORDS[COMP_CWORD-1]}"
          cmd="${COMP_WORDS[1]}"
          if [[ $COMP_CWORD -eq 1 ]]; then
            COMPREPLY=( $(compgen -W "\(names) --help --version" -- "$cur") )
            return
          fi
          local IFS=$'\\n'
          case "$prev" in

        """
        var valued: [String: CLIOption] = [:]
        for c in commands { for o in c.visibleOptions where o.takesValue { valued[o.name] = o } }
        for o in valued.values.sorted(by: { $0.name < $1.name }) {
            let flags = (["--\(o.name)"] + (o.short.map { ["-\($0)"] } ?? [])).joined(separator: "|")
            let action: String
            switch o.completion {
            case .printers: action = #"COMPREPLY=( $(compgen -W "$("${COMP_WORDS[0]}" printers --names 2>/dev/null)" -- "$cur") )"#
            case .sizes: action = #"COMPREPLY=( $(compgen -W "$("${COMP_WORDS[0]}" sizes --names 2>/dev/null)" -- "$cur") )"#
            case .directory: action = #"COMPREPLY=( $(compgen -d -- "$cur") )"#
            case .choices: action = "COMPREPLY=( $(compgen -W \"\(o.choices.joined(separator: "\n"))\" -- \"$cur\") )"
            default: action = "COMPREPLY=()"
            }
            s += "    \(flags)) \(action); return ;;\n"
        }
        s += """
          esac
          case "$cmd" in

        """
        for c in commands {
            let opts = (c.visibleOptions + Manual.globalOptions).map { "--\($0.name)" }.joined(separator: " ")
            var extra = ""
            for a in c.arguments {
                switch a.completion {
                case .file: extra = " files=1;"
                case .printers: extra = " dirs=printers;"
                case .choices: extra = " dirs=\"\(a.choices.joined(separator: " "))\";"
                default: break
                }
            }
            s += "    " + ([c.name] + c.aliases).joined(separator: "|") + ") opts=\"\(opts)\";\(extra) ;;\n"
        }
        s += """
          esac
          if [[ "$cur" == -* ]]; then
            IFS=' '; COMPREPLY=( $(compgen -W "$opts" -- "$cur") )
          elif [[ -n "$files" ]]; then
            local f
            COMPREPLY=()
            for f in $(compgen -f -- "$cur"); do
              if [[ -d "$f" ]]; then COMPREPLY+=( "$f" ); continue; fi
              case "$(echo "${f##*.}" | tr '[:upper:]' '[:lower:]')" in
                \(extensions.joined(separator: "|"))) COMPREPLY+=( "$f" ) ;;
              esac
            done
          elif [[ "$dirs" == printers ]]; then
            COMPREPLY=( $(compgen -W "$("${COMP_WORDS[0]}" printers --names 2>/dev/null)" -- "$cur") )
          elif [[ -n "$dirs" ]]; then
            IFS=' '; COMPREPLY=( $(compgen -W "$dirs" -- "$cur") )
          fi
        }
        complete -o filenames -F _peelgood \(Manual.names.joined(separator: " "))

        """
        return s
    }

    // MARK: fish

    static func fish() -> String {
        var s = """
        # fish completion for \(Manual.tool). Generated by `peelgood completions fish`.
        function __peelgood_run
            set -l tool (commandline -opc)[1]
            command $tool $argv 2>/dev/null
        end

        for tool in \(Manual.names.joined(separator: " "))
            complete -c $tool -f

        """
        let all = commands.flatMap { [$0.name] + $0.aliases }.joined(separator: " ")
        for c in commands {
            for name in [c.name] + c.aliases {
                s += "    complete -c $tool -n 'not __fish_seen_subcommand_from \(all)' -a \(name) -d '\(short(c.summary))'\n"
            }
        }
        s += "    complete -c $tool -n 'not __fish_seen_subcommand_from \(all)' -s V -l version -d 'Show the version'\n"
        for c in commands {
            let cond = "-n '__fish_seen_subcommand_from \(([c.name] + c.aliases).joined(separator: " "))'"
            for o in c.visibleOptions + Manual.globalOptions {
                var line = "    complete -c $tool \(cond)"
                if let short = o.short { line += " -s \(short)" }
                line += " -l \(o.name)"
                if o.takesValue {
                    switch o.completion {
                    case .printers: line += " -x -a '(__peelgood_run printers --names)'"
                    case .sizes: line += " -x -a '(__peelgood_run sizes --names)'"
                    case .directory: line += " -r -a '(__fish_complete_directories)'"
                    case .choices: line += " -x -a '\(o.choices.joined(separator: " "))'"
                    default: line += " -x"
                    }
                }
                s += line + " -d '\(short(o.help))'\n"
            }
            for a in c.arguments {
                switch a.completion {
                case .file: s += "    complete -c $tool \(cond) -F\n"
                case .printers: s += "    complete -c $tool \(cond) -a '(__peelgood_run printers --names)'\n"
                case .choices: s += "    complete -c $tool \(cond) -a '\(a.choices.joined(separator: " "))'\n"
                default: break
                }
            }
        }
        s += "end\n"
        return s
    }
}
