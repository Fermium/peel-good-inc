import Foundation

/// peelgood(1) in roff, generated from `Manual`. The build scripts write it into the app bundle.
public enum ManPage {
    public static func roff(version: String = "", date: Date = Date()) -> String {
        let day = ISO8601DateFormatter.string(from: date, timeZone: .gmt, formatOptions: [.withFullDate])
        var r = """
        .\\" Generated by `peelgood man-page`. Edit Sources/LabelizeCLI/Manual.swift instead.
        .TH LABELIZE 1 "\(day)" "Peel Good Inc. \(esc(version))" "General Commands Manual"
        .SH NAME
        \(Manual.tool) \\- print any PDF, SVG or image as a thermal printer label
        .SH SYNOPSIS
        .B \(Manual.tool)
        .I command
        .RI [ options ]
        .RI [ file ...]
        .SH DESCRIPTION
        .B \(Manual.tool)
        is the command line for Peel Good Inc. It fits each page to the label size, converts it to black
        and white for the printer's dot grid and prints it with
        .BR lp (1).
        .PP
        Printer, size, ink, cutoff and calibration default to what you chose in the Peel Good Inc. app
        (read only, never changed), else the system's label printer at 4x6 inches.

        """
        r += ".SH COMMANDS\n"
        for c in Manual.visibleCommands {
            r += ".SS \(esc(c.usage()))\n"
            r += esc(c.summary) + ".\n"
            if !c.discussion.isEmpty { r += esc(c.discussion) + "\n" }
            if !c.aliases.isEmpty { r += ".br\nAlias: " + c.aliases.map { "\\fB\($0)\\fR" }.joined(separator: ", ") + ".\n" }
            for a in c.arguments { r += ".TP\n.I \(esc(a.name))\n\(esc(a.help))\n" }
            for o in c.visibleOptions { r += option(o) }
        }
        r += ".SH GLOBAL OPTIONS\n"
        for o in Manual.globalOptions { r += option(o) }
        r += ".TP\n.BR \\-V \", \" \\-\\-version\nShow the version.\n"

        r += ".SH EXAMPLES\n"
        for c in Manual.visibleCommands where c.name != "help" {
            for e in c.examples {
                r += ".TP\n.B \(esc(e.command))\n\(esc(e.comment)).\n"
            }
        }
        r += ".SH SHELL COMPLETION\nHomebrew installs completions. Otherwise:\n"
        for shell in Completions.Shell.allCases {
            r += ".TP\n\(shell.rawValue) (\(esc(shell.startupFile)))\n.B \(esc(shell.installLine))\n"
        }
        r += ".SH COMPATIBILITY\nThe flag\\-only form from earlier versions still works and prints the new form:\n"
        for l in Manual.legacy { r += ".TP\n.B \(esc(l.old))\nis\n.BR \"\(esc(l.new))\" .\n" }
        r += ".SH ENVIRONMENT\n"
        for e in Manual.environment { r += ".TP\n.B \(e.name)\n\(esc(e.help))\n" }
        r += """
        .SH FILES
        .TP
        .I ~/Library/Application Support/Peel Good/History
        Labels the app printed, read by \\fBhistory\\fR.
        .TP
        .I ~/Library/Application Support/Peel Good/server.json
        Where the app's local API listens, read by \\fBdoctor\\fR.
        .TP
        .I ~/Library/Preferences/com.fermiumlabs.labelize.plist
        The app's settings, read for defaults.
        .SH EXIT STATUS

        """
        for code in ExitCode.allCases { r += ".TP\n.B \(code.rawValue)\n\(esc(code.meaning))\n" }
        r += """
        .SH SEE ALSO
        .BR lp (1),
        .BR lpstat (1),
        .BR lpoptions (1)
        .PP
        Settings > CLI in Peel Good Inc. shows this manual and installs the command.

        """
        return r
    }

    static func option(_ o: CLIOption) -> String {
        var head = ".TP\n.BR " + (o.short.map { "\\-\($0) \", \" " } ?? "") + "\\-\\-\(o.name)"
        if let v = o.value { head += " \" \" \\fI\(esc(v))\\fR" }
        return head + "\n" + esc(o.help) + "\n"
    }

    /// Escapes backslashes and dashes, and keeps lines from starting with a control character.
    static func esc(_ s: String) -> String {
        var t = s.replacingOccurrences(of: "\\", with: "\\e").replacingOccurrences(of: "-", with: "\\-")
            .replacingOccurrences(of: "…", with: "...").replacingOccurrences(of: "“", with: "\"").replacingOccurrences(of: "”", with: "\"")
        if t.hasPrefix(".") || t.hasPrefix("'") { t = "\\&" + t }
        return t
    }
}
