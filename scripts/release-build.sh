#!/bin/bash
# CI-friendly build of "Peel Good Inc.app": universal binaries, version from the environment,
# Developer ID signing with hardened runtime, per-target entitlements. No lsregister/pbs/pluginkit.
#
# Environment (all optional):
#   VERSION        CFBundleShortVersionString, e.g. 1.2.3 (default 0.0.0)
#   BUILD_NUMBER   CFBundleVersion, monotonically increasing integer (default 1)
#   SIGN_IDENTITY  "Developer ID Application: Name (TEAMID)" or its SHA-1; "-" = ad hoc (default "-")
#   KEYCHAIN       keychain to sign from (CI temp keychain); default: search list
#   ARCHS          "arm64 x86_64" (default) or "arm64"
#   OUT_DIR        output folder (default build/release)
#
# Usage: scripts/release-build.sh          (run from anywhere; works on the repo root)
# Bash 3.2 compatible (macOS /bin/bash).
set -euo pipefail

ROOT="${REPO_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$ROOT"
SCRIPTS="$(cd "$(dirname "$0")" && pwd)"
ENT="$SCRIPTS/entitlements"

VERSION="${VERSION:-0.0.0}"
BUILD_NUMBER="${BUILD_NUMBER:-1}"
SIGN_IDENTITY="${SIGN_IDENTITY:--}"
ARCHS="${ARCHS:-arm64 x86_64}"
OUT_DIR="${OUT_DIR:-build/release}"
BUNDLE_ID="com.fermium.peelgood"
APP_NAME="Peel Good Inc."            # CFBundleName/DisplayName (trailing period is part of the name)
APP_BUNDLE="Peel Good Inc.app"      # folder name: not "$APP_NAME.app", which would give "Inc..app"
MIN_OS="15.0"

[[ "$VERSION" =~ ^[0-9]+(\.[0-9]+){0,2}$ ]] || { echo "VERSION must be N[.N[.N]], got '$VERSION'" >&2; exit 1; }
[[ "$BUILD_NUMBER" =~ ^[0-9]+(\.[0-9]+)*$ ]] || { echo "BUILD_NUMBER must be numeric, got '$BUILD_NUMBER'" >&2; exit 1; }

echo "==> $APP_NAME $VERSION ($BUILD_NUMBER), archs: $ARCHS, identity: $SIGN_IDENTITY"
xcrun swift --version

# ---------- 1. SwiftPM products (universal) ----------
arch_flags=()
for a in $ARCHS; do arch_flags+=(--arch "$a"); done

products="PeelGoodApp peelgood"
# Optional products, included when Package.swift declares them.
grep -q '"peel-good-mcp"' Package.swift && products="$products peel-good-mcp"

for p in $products; do
  swift build -c release "${arch_flags[@]}" --product "$p"
done
BIN="$(swift build -c release "${arch_flags[@]}" --show-bin-path)"
echo "bin path: $BIN"

# ---------- 2. Bundle layout ----------
APP="$OUT_DIR/$APP_BUNDLE"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Helpers"
cp "$BIN/PeelGoodApp" "$APP/Contents/MacOS/PeelGood"
# The CLI goes to Contents/Helpers, NOT Contents/MacOS: "peelgood" and "PeelGood" collide on
# case-insensitive APFS. The cask symlinks it onto PATH.
cp "$BIN/peelgood" "$APP/Contents/Helpers/peelgood"
if [[ -f "$BIN/peel-good-mcp" ]]; then
  cp "$BIN/peel-good-mcp" "$APP/Contents/MacOS/peel-good-mcp"
fi
cp Resources/*.wav Resources/PeelGood.icns docs/brand/icon.svg "$APP/Contents/Resources/"
cp docs/brand/logo-light.png docs/brand/logo-dark.png LICENSE "$APP/Contents/Resources/"
# Man page and shell completions, generated by the CLI from its own description (the
# universal binary runs on the build Mac). The cask links them into Homebrew's prefix.
mkdir -p "$APP/Contents/Resources/completions"
"$BIN/peelgood" man-page --release "$VERSION" > "$APP/Contents/Resources/peelgood.1"
"$BIN/peelgood" completions zsh > "$APP/Contents/Resources/completions/_peelgood"
"$BIN/peelgood" completions bash > "$APP/Contents/Resources/completions/peelgood.bash"
"$BIN/peelgood" completions fish > "$APP/Contents/Resources/completions/peelgood.fish"
python3 scripts/make-sbom.py "$VERSION" "$APP/Contents/Resources/sbom.cdx.json"

# Share extension (SwiftPM can't make .appex): one swiftc per arch, then lipo.
APPEX="$APP/Contents/PlugIns/PeelGoodShare.appex"
mkdir -p "$APPEX/Contents/MacOS"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
slices=()
for a in $ARCHS; do
  xcrun swiftc -O -parse-as-library -application-extension -module-name PeelGoodShare \
    -target "$a-apple-macos$MIN_OS" -Xlinker -e -Xlinker _NSExtensionMain \
    Extensions/Share/ShareViewController.swift Sources/PeelGoodShared/AppIdentity.swift -o "$TMP/PeelGoodShare-$a"
  slices+=("$TMP/PeelGoodShare-$a")
done
xcrun lipo -create "${slices[@]}" -output "$APPEX/Contents/MacOS/PeelGoodShare"

source "$SCRIPTS/info-plists.sh"
write_info_plists "$APP/Contents" "$APPEX/Contents"
printf 'APPL????' > "$APP/Contents/PkgInfo"

# ---------- 3. Sign, inside out (no --deep) ----------
sign_flags=(--force --sign "$SIGN_IDENTITY")
if [[ "$SIGN_IDENTITY" == "-" ]]; then
  sign_flags+=(--timestamp=none)          # ad hoc: no secure timestamp possible
else
  sign_flags+=(--options runtime --timestamp)   # required by notarization
fi
[[ -n "${KEYCHAIN:-}" ]] && sign_flags+=(--keychain "$KEYCHAIN")

sign() {  # sign <path> <entitlements> [identifier]
  local id_flags=()
  [[ -n "${3:-}" ]] && id_flags=(--identifier "$3")
  codesign "${sign_flags[@]}" ${id_flags[@]+"${id_flags[@]}"} --entitlements "$2" "$1"
}

# 3a. bare executables that are not the bundle's main executable
sign "$APP/Contents/Helpers/peelgood" "$ENT/Helper.entitlements" "$BUNDLE_ID.cli"
if [[ -f "$APP/Contents/MacOS/peel-good-mcp" ]]; then
  sign "$APP/Contents/MacOS/peel-good-mcp" "$ENT/Helper.entitlements" "$BUNDLE_ID.mcp"
fi
# 3b. nested bundles
sign "$APPEX" "$ENT/Share.entitlements"
# 3c. the app itself, last
sign "$APP" "$ENT/PeelGood.entitlements"

# ---------- 4. Verify ----------
codesign --verify --deep --strict --verbose=2 "$APP"
codesign -dvv "$APP" 2>&1 | grep -E 'Identifier|Authority|TeamIdentifier|flags|Timestamp' || true
for f in "$APP/Contents/MacOS/PeelGood" "$APP/Contents/Helpers/peelgood" "$APPEX/Contents/MacOS/PeelGoodShare"; do
  echo "$(basename "$f"): $(xcrun lipo -archs "$f")"
done
echo "built $APP"
